function apply_sd_plot_style(fig, ax, style)
%APPLY_SD_PLOT_STYLE Apply the shared physical and axes settings.

set(fig, ...
    'Color', style.backgroundColor, ...
    'Units', 'inches', ...
    'Position', [0.5 0.5 style.figureWidthIn style.figureHeightIn], ...
    'PaperPositionMode', 'auto');
set(ax, ...
    'FontName', style.fontName, ...
    'FontSize', style.fontSizeTick, ...
    'LineWidth', style.axesLineWidth, ...
    'XColor', style.axesColor, ...
    'YColor', style.axesColor, ...
    'GridColor', style.gridColor, ...
    'GridAlpha', style.gridAlpha, ...
    'GridLineStyle', '-', ...
    'TickDir', 'out', ...
    'Box', 'on');
grid(ax, 'on');

end
