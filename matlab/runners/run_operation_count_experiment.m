function results = run_operation_count_experiment( ...
        mode, ambiguityOrdering, outputFile)
%RUN_OPERATION_COUNT_EXPERIMENT Experiment 5: discrete reduction operations.
%   Uses the same random-dimension matrices as Experiment 2. Each input
%   matrix is counted once; no timing or FLOP result is produced.

arguments
    mode (1, 1) string {mustBeMember(mode, ["pilot", "full"])} = "pilot"
    ambiguityOrdering (1, 1) string {mustBeMember(ambiguityOrdering, ...
        ["variance-ordered", "random-order"])} = "random-order"
    outputFile (1, 1) string = ""
end

paths = setup_sd_experiment_paths();
config = sd_experiment_config(mode, ambiguityOrdering);
outputDirectory = fullfile(paths.numericalOutput, mode);
if ambiguityOrdering == "random-order"
    outputDirectory = fullfile(outputDirectory, 'random_order');
end
manifest = read_cached_experiment_manifest( ...
    paths.cache, mode, ambiguityOrdering, true);
settings = manifest(string(manifest.Family) == "random-dimension", :);
settings = settings(ismember(settings.Dimension, config.dimensionValues), :);
if height(settings) ~= numel(config.dimensionValues)
    error('run_operation_count_experiment:IncompleteCache', ...
        'The random-dimension cache does not cover all Experiment 2 settings.');
end

if strlength(outputFile) == 0
    if ~exist(outputDirectory, 'dir'), mkdir(outputDirectory); end
    outputFile = fullfile(outputDirectory, ...
        'exp05_reduction_operations_dimension.tsv');
else
    explicitDirectory = fileparts(outputFile);
    if strlength(explicitDirectory) > 0 && ~exist(explicitDirectory, 'dir')
        mkdir(explicitDirectory);
    end
end

names = {'Family','Dimension','NumMatrices', ...
    'CDReductionIGTMean','CDReductionIGTStd', ...
    'SDInheritanceIGTMean','SDReductionIGTMean', ...
    'SDTotalIGTMean','SDTotalIGTStd','IGTCountRatio', ...
    'CDReductionSwapMean','CDReductionSwapStd', ...
    'SDInheritanceSwapMean','SDReductionSwapMean', ...
    'SDTotalSwapMean','SDTotalSwapStd','SwapCountRatio'};
types = [{'string'}, repmat({'double'}, 1, numel(names)-1)];
results = table('Size', [height(settings), numel(names)], ...
    'VariableTypes', types, 'VariableNames', names);

for settingIndex = 1:height(settings)
    fprintf('Experiment 5 (operation counts): setting %d/%d\n', ...
        settingIndex, height(settings));
    cached = load(char(string(settings.File(settingIndex))), ...
        'matrices', 'metadata');
    matrices = cached.matrices;
    numMatrices = size(matrices, 3);
    if numMatrices ~= config.numRandomMatrices || ...
            size(matrices, 1) ~= settings.Dimension(settingIndex) || ...
            size(matrices, 2) ~= settings.Dimension(settingIndex)
        error('run_operation_count_experiment:CacheMismatch', ...
            'Cached matrices do not match the Experiment 2 configuration.');
    end
    if isfield(cached, 'metadata') && isfield(cached.metadata, 'ordering') ...
            && string(cached.metadata.ordering) ~= ambiguityOrdering
        error('run_operation_count_experiment:OrderingMismatch', ...
            'The cached ambiguity ordering does not match the configuration.');
    end
    counts = zeros(numMatrices, 8);
    for sampleIndex = 1:numMatrices
        eventCounts = count_cd_sd_reduction_operations( ...
            matrices(:, :, sampleIndex));
        counts(sampleIndex, :) = [ ...
            eventCounts.cdReductionIGT, ...
            eventCounts.sdInheritanceIGT, ...
            eventCounts.sdReductionIGT, ...
            eventCounts.sdTotalIGT, ...
            eventCounts.cdReductionSwaps, ...
            eventCounts.sdInheritanceSwaps, ...
            eventCounts.sdReductionSwaps, ...
            eventCounts.sdTotalSwaps];
    end

    means = mean(counts, 1);
    stds = std(counts, 0, 1);
    results(settingIndex, :) = {"random-dimension", ...
        settings.Dimension(settingIndex), numMatrices, ...
        means(1), stds(1), means(2), means(3), means(4), stds(4), ...
        means(1) / max(means(4), eps), ...
        means(5), stds(5), means(6), means(7), means(8), stds(8), ...
        means(5) / max(means(8), eps)};
    writetable(results(1:settingIndex, :), outputFile, ...
        'FileType', 'text', 'Delimiter', '\t');
end

end
